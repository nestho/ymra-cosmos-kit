function weeksHtml(phase) {
  const rows = window.WEEKS.filter((w) => !phase || w.phase === phase);
  return rows
    .map((w) => {
      const open = w.open ? " open" : "";
      const parts = [];
      if (w.astro) parts.push(`<div class="tag">نجوم</div>${list(w.astro)}`);
      if (w.algo) parts.push(`<div class="tag">الگوریتم</div>${list(w.algo)}`);
      if (w.tess) parts.push(`<div class="tag">TESS</div>${list(w.tess)}`);
      if (w.admin) parts.push(`<div class="tag">اداری</div>${list(w.admin)}`);
      return `<details class="week"${open}><summary>${w.when} — ${w.title}</summary><div class="week-body">${parts.join("")}</div></details>`;
    })
    .join("");
}

